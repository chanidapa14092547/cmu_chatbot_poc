let currentLang = "th";

function toggleLanguage() {
    currentLang = currentLang === "en" ? "th" : "en";
    updateLanguage();
}

function updateLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[currentLang][key]) {
            let text = i18n[currentLang][key];
            const args = el.getAttribute('data-i18n-args');
            if (args) {
                try {
                    const parsedArgs = JSON.parse(args.replace(/&quot;/g, '"'));
                    for (const [k, v] of Object.entries(parsedArgs)) {
                        let translatedV = i18n[currentLang][v] || v;
                        text = text.replace(`{${k}}`, translatedV);
                    }
                } catch(e) {}
            }
            if (el.tagName.toLowerCase() === 'input' && el.type === 'text') {
                el.placeholder = text;
            } else {
                el.innerHTML = text;
            }
        }
    });
    
    // Also update dynamic remaining text if possible, but for now we just change static
    const langBtn = document.getElementById('lang-btn');
    if (langBtn) langBtn.innerHTML = i18n[currentLang]["btn-lang"];

    // Update minor options manually
    document.querySelectorAll('.minor-select option').forEach(opt => {
        opt.textContent = window.formatMinorOption(opt.value, currentLang);
    });

    window.dispatchEvent(new Event('languageChanged'));
}

document.addEventListener('DOMContentLoaded', updateLanguage);

window.formatMinorOption = function(m, lang) {
    if (m === "none" || m === "") {
        return lang === 'en' ? "Major Elective / Advanced Courses (300-400)" : "เรียนวิชาระดับ 300-400 แทน 15 หน่วยกิต (Major Electives)";
    }
    // Clean up internal PDF page references like [ฉบับหน้า 5]
    m = m.replace(/\s*\[ฉบับหน้า\s*\d+\]/g, '');
    
    const match = m.match(/^([^(]+)(?:\s*\(([^)]+)\))?(.*)/);
    let th = match ? match[1].trim() : m;
    let en = match && match[2] ? match[2].trim() : th;
    let trail = match && match[3] ? match[3].trim() : "";
    
    if (lang === 'en') {
        if (trail) {
            trail = trail.replace(/\(ยกเว้น\s*นักศึกษารหัสบริหารธุรกิจรหัส\s*68\s*เป็นต้นไป\)/, "(except Business Admin ID 68+)");
            trail = trail.replace(/\(\*ยกเว้นนักศึกษาสาขาวิชาวิศวกรรมอุตสาหการ\)/, "(*except Industrial Eng.)");
            trail = trail.replace(/\[ปิดสอน ตั้งแต่ 1\/2567 เป็นต้นไป\]/, "[Closed from 1/2567 onwards]");
            trail = trail.replace(/ยกเว้น/g, "except");
        }
        return trail ? `Minor: ${en} ${trail}` : `Minor: ${en}`;
    } else {
        // For Thai, keep the full original string to preserve all remarks
        // Strip duplicate prefix if m already starts with "วิชาโท"
        if (m.startsWith("วิชาโท")) {
            return m;
        }
        return `วิชาโท: ${m}`;
    }
};

window.t = function(key, replacements = {}) {
    let text = i18n[currentLang][key] || key;
    for (const [k, v] of Object.entries(replacements)) {
        text = text.replace(`{${k}}`, v);
    }
    return text;
};
